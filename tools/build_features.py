#!/usr/bin/env python3
"""
Builds features/*.lua from TerkanUniversal.lua.

Every feature becomes a file that runs on its own: it loads features/_core.lua (the shared helpers of the hub:
config table, toggle/slider/dropdown helpers, notifications, targeting ...), opens a small menu with just that
feature and runs the same code as the hub. The code is taken straight from the hub, so the files follow every
update of it: change the hub, run this script, commit.

    python tools/build_features.py                      # hub = ./TerkanUniversal.lua, output = ./features
    python tools/build_features.py --hub ../x.lua --out ../features

The manifest at the bottom says which lines of the hub belong to which feature.
"""
import argparse
