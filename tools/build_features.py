def identifiers(text):
    # strip comments and strings well enough for a name scan
    text = re.sub(r"--\[\[.*?\]\]", "", text, flags=re.S)
    text = re.sub(r"--[^\n]*", "", text)
    text = re.sub(r'"(?:\\.|[^"\\\n])*"', '""', text)
    text = re.sub(r"'(?:\\.|[^'\\\n])*'", "''", text)
    return set(re.findall(r"\b[A-Za-z_][A-Za-z0-9_]*\b", text))


def build_feature(hub, f, exported):
    prelude = []
    if f["tab"]:
        prelude.append('local %s = win:Tab("%s")' % (f["tabvar"], f["tab"]))
        for var, title, side in f["secs"]:
            if title is None:
                continue
            args = '"%s"' % title + (', "%s"' % side if side else "")
            prelude.append("local %s = %s:Section(%s)" % (var, f["tabvar"], args))
    if f["pre"]:
        prelude.append(f["pre"])
    if f["picker"]:
        prelude.append("local playerDD = addPlayerPicker(%s)" % f["picker"])
    body = "\n\n".join(cut(hub, a, b) for a, b in f["code"])
    code = "\n".join(prelude) + "\n\n" + body if prelude else body

    used = sorted({n for n in identifiers(code) if n in exported and n != "slot"} | {"Ready"})
    header = FEATURE_HEADER % dict(title=f["title"], name=f["name"], about=f["about"], base=BASE_URL,
                                   repo="https://github.com/tygovansteenpaalwork-gif/Roblox_lua_script")
    # ctx names as locals, in chunks of a readable width
    decl = []
    for i in range(0, len(used), 6):
        chunk = used[i:i + 6]
        decl.append("local %s = %s" % (", ".join(chunk), ", ".join("ctx." + n for n in chunk)))
    return header + "\n" + "\n".join(decl) + "\n\n" + code + "\n\nReady()\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub", default=os.path.join(root, "TerkanUniversal.lua"))
    ap.add_argument("--out", default=os.path.join(root, "features"))
    args = ap.parse_args()

    hub = Hub(args.hub)
    os.makedirs(args.out, exist_ok=True)
    core, exported = build_core(hub)
    ex = set(exported)

    def write(name, text):
        with io.open(os.path.join(args.out, name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)

    write("_core.lua", core)
    for f in FEATURES:
        write(f["name"] + ".lua", build_feature(hub, f, ex))
    for name, target, about in ALIASES:
        write(name + ".lua", ALIAS_TEMPLATE % dict(name=name, target=target, about=about, base=BASE_URL))

    # index
    rows = ["# Terkan features", "",
            "Every feature of the Terkan Universal hub as a file of its own, so you can find it by name. Each file runs "
            "on its own (a small menu with just that feature) and is the same code as in the hub.", "",
            "```lua", 'loadstring(game:HttpGet("%sfeatures/desync.lua"))()' % BASE_URL, "```", "",
            "| File | What it does |", "| --- | --- |"]
    entries = [(f["name"], f["about"]) for f in FEATURES] + [(n, a + " (pointer)") for n, _, a in ALIASES]
    for name, about in sorted(entries):
        rows.append("| [`%s.lua`](%s.lua) | %s |" % (name, name, about))
    rows += ["", "`_core.lua` holds the shared helpers (config table, toggle/slider helpers, notifications, targeting ...). "
             "Everything here is generated (`python tools/build.py`); edit `src/` and rebuild, not these files. `manifest.json` is the machine readable index that `Terkan.lua` uses.", ""]
    write("README.md", "\n".join(rows))

    # files of features that no longer exist in the manifest are removed
    keep = {"_core.lua", "README.md"} | {f["name"] + ".lua" for f in FEATURES} | {n + ".lua" for n, _, _ in ALIASES}
    for stale in sorted(os.listdir(args.out)):
        if stale.endswith((".lua", ".md")) and stale not in keep:
            os.remove(os.path.join(args.out, stale))
            print("removed stale", stale)
    print("wrote %d features, %d pointers, core with %d exports" % (len(FEATURES), len(ALIASES), len(exported)))


if __name__ == "__main__":
    main()
