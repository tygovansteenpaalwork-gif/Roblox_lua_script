import re

BASE_URL = "https://raw.githubusercontent.com/tygovansteenpaalwork-gif/Roblox_lua_script/main/"


# --------------------------------------------------------------------------------------------- helpers

class Hub:
    def __init__(self, path):
        with io.open(path, encoding="utf-8") as f:
            self.lines = f.read().replace("\r\n", "\n").split("\n")

    def find(self, pattern, start=0):
        rx = re.compile(pattern)
        for i in range(start, len(self.lines)):
            if rx.search(self.lines[i]):
                return i
        raise SystemExit("marker not found: %r (searching from line %d)" % (pattern, start + 1))

    def banner(self, title):
        """index of the first line after the 3-line banner ('-----' / '-- tab: Title' / '-----')"""
        return self.find(r"^-- tab: " + re.escape(title)) + 2

    def banner_start(self, title):
        return self.find(r"^-- tab: " + re.escape(title)) - 1

    def text(self, a, b):
        return "\n".join(self.lines[a:b]).strip("\n")


# Markers for the ranges of the manifest:
#   "after:Title"   first line after the banner of the tab "Title"
#   "before:Title"  the first line of that tab's banner (exclusive end)
#   "at:regex"      the first line matching regex (at or after the start of the range)
#   "incl:regex"    the line AFTER the first line matching regex (to include that line at an end)
def resolve(hub, spec, start_from=0):
    kind, _, rest = spec.partition(":")
    if kind == "after":
        return hub.banner(rest)
    if kind == "before":
        return hub.banner_start(rest)
    if kind == "at":
        return hub.find(rest, start_from)
    if kind == "incl":
        return hub.find(rest, start_from) + 1
    raise SystemExit("bad marker " + spec)


def cut(hub, a, b):
    ia = resolve(hub, a)
    ib = resolve(hub, b, ia + 1)
    return hub.text(ia, ib)


